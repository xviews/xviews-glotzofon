let LANG = 'de';

function t(s, vars) {
  let r = (LANG === 'en' && I18N_EN[s]) || s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return r;
}

// Übersetzt alle statischen Texte und Attribute. Der deutsche Originaltext wird am Knoten gemerkt,
// damit man jederzeit zurückschalten kann.
function applyI18n(root = document.body) {
  const norm = (s) => s.replace(/\s+/g, ' ').trim();
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const n = walker.currentNode;
    if (n.parentElement.closest('script,style,svg,pre,code')) continue;
    if (n.__de === undefined) n.__de = n.nodeValue;
    const key = norm(n.__de);
    if (!key) continue;
    const lead = n.__de.match(/^\s*/)[0];
    const trail = n.__de.match(/\s*$/)[0];
    n.nodeValue = lead + t(key) + trail;
  }
  for (const attr of ['placeholder', 'title', 'aria-label']) {
    root.querySelectorAll('[' + attr + ']').forEach((el) => {
      const store = 'de' + attr.replace(/-./g, (m) => m[1].toUpperCase());
      if (el.dataset[store] === undefined) el.dataset[store] = el.getAttribute(attr);
      el.setAttribute(attr, t(el.dataset[store]));
    });
  }
}

// lang: "auto" (Windows- bzw. Browsersprache), "de" oder "en"
function setLanguage(lang) {
  const sys = (navigator.language || 'de').toLowerCase();
  LANG = lang === 'de' || lang === 'en' ? lang : sys.startsWith('de') ? 'de' : 'en';
  document.documentElement.lang = LANG;
  applyI18n();
  if (typeof window.setLang === 'function') window.setLang(LANG).catch(() => {}); // Go: Menü im Infobereich
}
